"""Filter Serializer for FILTER-01.

Serializes generated rules into valid PoE2 .filter file format.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from typing import List, Optional

from exilelens.filters.rules import GeneratedRule
from exilelens.filters.profiles import FilterProfile, BuildFingerprint


@dataclass
class FilterMetadata:
    """Metadata for the generated filter."""
    build_name: str
    class_name: str
    ascendancy: str
    main_skill: str
    profile_name: str
    generated_at: datetime
    source_revision: str
    version: str = "FILTER-08C-INTEL-01"
    theme_name: str = ""
    # FILTER-08C: where the build-aware decisions came from. Empty for the legacy generator.
    intelligence: str = ""
    intelligence_notes: str = ""
    data_state: str = ""


class FilterSerializer:
    """Serializes filter rules to .filter file format."""

    def __init__(self, metadata: FilterMetadata):
        self.metadata = metadata

    def serialize(self, rules: List[GeneratedRule]) -> str:
        """Serialize rules to filter text."""
        lines = []

        # Header
        lines.append(self._generate_header())
        lines.append("")

        # Table of contents
        lines.append(self._generate_toc(rules))
        lines.append("")

        # Rules by category
        current_category = None
        for rule in rules:
            if rule.category != current_category:
                if current_category is not None:
                    lines.append("")
                lines.append(f"#===============================================================================================================")
                lines.append(f"# [[{rule.category}]]")
                lines.append(f"#===============================================================================================================")
                lines.append("")
                current_category = rule.category

            # Rule comment
            if rule.name:
                lines.append(f"# {rule.name}")

            # Rule lines
            lines.extend(rule.lines)

        # Footer
        lines.append("")
        lines.append("#===============================================================================================================")
        lines.append("# END OF FILTER")
        lines.append("#===============================================================================================================")

        text = "\n".join(lines)
        # fail closed: never hand out a filter whose BaseType values are not native ground bases (the game parser must not be the first
        # validator of a base name)
        from exilelens.filters.native_bases import assert_native_base_types
        assert_native_base_types(text)
        return text

    def _generate_header(self) -> str:
        """Generate filter header."""
        generated_utc = self.metadata.generated_at.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")
        return "\n".join([
            "#===============================================================================================================",
            f"# ExileLens Build-Aware Loot Filter",
            f"# Build: {self.metadata.build_name} ({self.metadata.class_name}/{self.metadata.ascendancy})",
            f"# Main Skill: {self.metadata.main_skill}",
            f"# Profile: {self.metadata.profile_name}",
            f"# Theme: {self.metadata.theme_name}",
            f"# Generated: {generated_utc}",
            f"# Version: {self.metadata.version}",
            f"# Source Revision: {self.metadata.source_revision}",
            *([f"# Build Intelligence: {self.metadata.intelligence}"] if self.metadata.intelligence else []),
            *([f"# Intelligence Notes: {self.metadata.intelligence_notes}"] if self.metadata.intelligence_notes else []),
            *([f"# Data: {self.metadata.data_state}"] if self.metadata.data_state else []),
            "#===============================================================================================================",
            "# This filter was generated by ExileLens FILTER-01 experimental module.",
            "# Build matches and heuristic trade candidates use verified base names.",
            "# Trade candidate labels are not live prices; verify final behaviour in game.",
            "# Market evidence: HEURISTIC; no current league valuation used during generation.",
            "#===============================================================================================================",
        ])

    def _generate_toc(self, rules: List[GeneratedRule]) -> str:
        """Generate table of contents."""
        lines = ["# [[TOC]] TABLE OF CONTENTS"]

        categories = []
        for rule in rules:
            if rule.category not in categories:
                categories.append(rule.category)

        for i, cat in enumerate(categories, 1):
            lines.append(f"# [[{i:04d}]] {cat}")

        return "\n".join(lines)

    def write_file(self, rules: List[GeneratedRule], path: str) -> None:
        """Write filter to file."""
        content = self.serialize(rules)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)


def create_metadata_from_fingerprint(
    fingerprint: BuildFingerprint,
    profile: FilterProfile,
) -> FilterMetadata:
    """Create filter metadata from fingerprint and profile."""
    return FilterMetadata(
        build_name=fingerprint.build_name,
        class_name=fingerprint.class_name,
        ascendancy=fingerprint.ascendancy,
        main_skill=fingerprint.main_skill,
        profile_name=profile.name.value,
        generated_at=fingerprint.generated_at,
        source_revision=fingerprint.source_revision,
        theme_name=profile.theme.value,
    )
